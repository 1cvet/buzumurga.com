import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
// Small HTML helpers shared by the templates.

export function esc(value) {
    return String(value)
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;');
}

export const attr = esc;

// Attributes for links that leave the site.
export const ext = ' target="_blank" rel="noopener"';

// Minimal inline markup for content strings: [text](https://url) and *emphasis*.
export function md(value) {
    return esc(value)
        .replace(/\[([^\]]+)\]\((https?:\/\/[^)\s]+)\)/g, (_, text, href) => `<a href="${href}"${ext}>${text}</a>`)
        .replace(/\*([^*]+)\*/g, '<em>$1</em>');
}

export function initials(name) {
    return name.split(/\s+/).map(part => part[0]).join('').slice(0, 2).toUpperCase();
}

// The email address is not written to the HTML as plain text:
// it is reversed and base64-encoded, js/main.js decodes it.
export function obfuscate(email) {
    return Buffer.from([...email].reverse().join(''), 'utf8').toString('base64');
}

// Icons for every page (files in static/, regenerated by scripts/icons.py).
// apple-touch-icon is opaque and full bleed: iOS rounds the corners itself.
// Icon URLs carry a content hash (?v=...), so browsers and iOS home screens
// pick up a new icon right away instead of serving a cached old one.
const staticDir = fileURLToPath(new URL('../static/', import.meta.url));
const v = file => createHash('sha256').update(readFileSync(staticDir + file)).digest('hex').slice(0, 8);
export const ICON_LINKS = `    <link rel="icon" href="/favicon.ico?v=${v('favicon.ico')}" sizes="32x32">
    <link rel="icon" href="/favicon.svg?v=${v('favicon.svg')}" type="image/svg+xml">
    <link rel="apple-touch-icon" href="/apple-touch-icon.png?v=${v('apple-touch-icon.png')}">
    <link rel="manifest" href="/site.webmanifest?v=${v('site.webmanifest')}">
    <meta name="apple-mobile-web-app-title" content="Buzumurga">`;

// schema.org BreadcrumbList: [[name, absoluteUrl], ...]
export function breadcrumbs(items) {
    return {
        '@type': 'BreadcrumbList',
        itemListElement: items.map(([name, item], i) => ({ '@type': 'ListItem', position: i + 1, name, item })),
    };
}
